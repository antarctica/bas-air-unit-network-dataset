from dataclasses import dataclass, field
from enum import Enum
from typing import ClassVar, Optional, Self

from lxml.etree import Element, SubElement

from bas_air_unit_network_dataset.exporters.fpl import Namespaces
from bas_air_unit_network_dataset.exporters.fpl.utils import upper_alphanumeric_only, upper_alphanumeric_space_only
from bas_air_unit_network_dataset.models.base.route import Route as BaseRoute
from bas_air_unit_network_dataset.models.base.route_waypoint import RouteWaypoint as BaseRouteWaypoint
from bas_air_unit_network_dataset.models.base.waypoint import Waypoint as BaseWaypoint


class WaypointType(Enum):
    """
    FPL waypoint type.

    The FPL standard defines several types of waypoint defined in the `fpl_waypoint_types` list and which include:
    - "USER WAYPOINT": user defined
    - "AIRPORT": airport
    - "INT": intersection
    - "VOR": Very High Frequency Omnidirectional Station
    - etc.

    Note: This library does not validate any requirements that might apply to specific waypoint types, other than what
    may be specified in the FPL XML XSD. Where types other than 'USER WAYPOINT' are used, it is possible an apparently
    valid FPL can be generated by this library but which is marked invalid when imported into a device.
    """

    USER_WAYPOINT = "USER WAYPOINT"
    AIRPORT = "AIRPORT"
    INT = "INT"
    VOR = "VOR"


@dataclass
class Waypoint:
    """
    FPL waypoint.

    Representation of a base waypoint within a FPL document.

    Identifier
    ----------

    The FPL standard uses identifiers as foreign keys for referencing waypoints within routes, identifiers should
    therefore be unique values.

    The FPL standard restricts waypoint identifiers to 19 characters, however when listing waypoints, GPS devices may
    only display up to 17 characters. To avoid losing potentially crucial information, this library therefore considers
    17 to be the effective limit, and will raise a ValueError exception if the length ia longer.

    Identifiers must consist of upper case alphanumeric characters (A-Z 0-9) only. Values containing invalid characters
    will be silently dropped.

    For example an identifier:
    > 'FOO-bar-ABCDEF' (14 characters)
    will become:
    > 'FOOABCDEF' (9 characters).

    Waypoint Type
    -------------

    See `WaypointType`.

    Country Code
    ------------

    The FPL standard restricts country codes to 2 characters, which must consist of upper case alphanumeric characters
    (A-Z 0-9) only. Values containing invalid characters will be silently dropped, except where noted below.

    A double underscore ('__') is sometimes used as the country code for Antarctica, rather than it's ISO 2-digit
    country code, 'AQ'. This value is invalid according to the FPL standard but has been used successfully in devices
    so is allowed as an exception to comply with existing usage.

    Longitude / Latitude
    --------------------

    The FPL standard assumes geometries are (single) points using the EPSG:4326 CRS.

    Longitude values outside ±180, or latitude values outside ±90 will raise a ValueError exception.

    **Note:** The FPL standard does not allow values to use `180.0/90.0` and `-180.0/-90.0` exactly. This method will
    automatically convert values to be the closest allowed values (`±179.999999 / ±89.999999`).

    COMMENT
    -------

    The FPL standard restricts waypoint comments to 25 characters, longer values will raise a ValueError exception.

    Comments must consist of upper case alphanumeric characters (A-Z 0-9), or spaces (' ') as a separator, only.
    Comments containing invalid characters will be silently dropped.

    For example a comment:
    > 'FOO-bar-ABC 123 DEF 456 G' (25 characters)
    will become:
    > 'FOOABC 123 DEF 456 G' (20 characters).
    """

    _ns = Namespaces()
    _max_identifier_length: ClassVar[int] = 17
    _max_country_code_length: ClassVar[int] = 2
    _max_comment_length: ClassVar[int] = 25
    _comment_placeholder: ClassVar[str] = "NO COMMENT"

    identifier: str
    longitude: float
    latitude: float
    type_: WaypointType = WaypointType.USER_WAYPOINT
    country_code: str = "__"
    comment: Optional[str] = _comment_placeholder

    def __post_init__(self) -> None:
        """Post-initialisation validation and processing."""
        self.identifier = self.process_identifier(self.identifier)
        self.country_code = self.process_country_code(self.country_code)
        self.longitude, self.latitude = self._process_lat_lon(self.longitude, self.latitude)
        self.comment = self._process_comment(self.comment)

    @staticmethod
    def process_identifier(identifier: str) -> str:
        """Validate and format identifier."""
        if len(identifier) > Waypoint._max_identifier_length:
            msg = f"Identifier must be {Waypoint._max_identifier_length} characters or less."
            raise ValueError(msg)
        return upper_alphanumeric_only(identifier)

    @staticmethod
    def process_country_code(country_code: str) -> str:
        """Validate and format country code."""
        if country_code == "__":
            return country_code
        if len(country_code) > Waypoint._max_country_code_length:
            msg = f"Country code must be {Waypoint._max_country_code_length} characters or less."
            raise ValueError(msg)
        return upper_alphanumeric_only(country_code)

    @staticmethod
    def _process_lat_lon(lon: float, lat: float) -> tuple[float, float]:
        """Validate and format latitude and longitude."""
        if not -180 <= lon <= 180:
            msg = "Longitude must be between -180 and +180."
            raise ValueError(msg)
        if lon == -180:
            lon = -179.999999
        elif lon == 180:
            lon = 179.999999

        if not -90 <= lat <= 90:
            msg = "Latitude must be between -90 and +90."
            raise ValueError(msg)
        if lat == 90:
            lat = 89.999999
        elif lat == -90:
            lat = -89.999999

        return lon, lat

    @staticmethod
    def _process_comment(comment: str | None) -> str:
        """Validate and format comment."""
        comment = comment or Waypoint._comment_placeholder
        if len(comment) > Waypoint._max_comment_length:
            msg = f"Comments must be {Waypoint._max_comment_length} characters or less."
            raise ValueError(msg)
        return upper_alphanumeric_space_only(comment)

    @classmethod
    def loads(cls, waypoint: BaseWaypoint) -> Self:
        """
        Load a base waypoint as an FPL waypoint.

        FPL waypoint type and country codes are hard-coded.
        """
        return Waypoint(
            identifier=waypoint.identifier,
            longitude=waypoint.geometry.x,
            latitude=waypoint.geometry.y,
            type_=WaypointType.USER_WAYPOINT,
            country_code="__",
            comment=waypoint.name.upper() if waypoint.name else Waypoint._comment_placeholder,
        )

    def dumps(self) -> Element:
        """Build an XML element for a FPL waypoint."""
        waypoint = Element(f"{{{self._ns.fpl}}}waypoint", nsmap=self._ns.nsmap())

        identifier = SubElement(waypoint, f"{{{self._ns.fpl}}}identifier")
        identifier.text = self.identifier

        type_ = SubElement(waypoint, f"{{{self._ns.fpl}}}type")
        type_.text = self.type_.value

        country_code = SubElement(waypoint, f"{{{self._ns.fpl}}}country-code")
        country_code.text = self.country_code

        latitude = SubElement(waypoint, f"{{{self._ns.fpl}}}lat")
        latitude.text = str(round(self.latitude, ndigits=7))

        longitude = SubElement(waypoint, f"{{{self._ns.fpl}}}lon")
        longitude.text = str(round(self.longitude, ndigits=7))

        if self.comment is not None:
            comment = SubElement(waypoint, f"{{{self._ns.fpl}}}comment")
            comment.text = self.comment

        return waypoint


@dataclass
class RouteWaypoint:
    """
    FPL route waypoint.

    Representation of a base route waypoint within a FPL document.

    Waypoint identifiers are references to a set of waypoints defined separately and taken at face value.
    """

    _ns = Namespaces()

    waypoint_identifier: str
    country_code: str
    type_: WaypointType = WaypointType.USER_WAYPOINT

    def __post_init__(self) -> None:
        """Post-initialisation validation and processing."""
        self.waypoint_identifier = Waypoint.process_identifier(self.waypoint_identifier)
        self.country_code = Waypoint.process_country_code(self.country_code)

    @classmethod
    def loads(cls, route_waypoint: BaseRouteWaypoint) -> Self:
        """
        Load a base route waypoint as an FPL route waypoint.

        FPL waypoint type and country codes are hard-coded.
        """
        return RouteWaypoint(
            waypoint_identifier=route_waypoint.waypoint.identifier, type_=WaypointType.USER_WAYPOINT, country_code="__"
        )

    def dumps(self) -> Element:
        """Build an XML element for a FPL route waypoint."""
        route_point = Element(f"{{{self._ns.fpl}}}route-point", nsmap=self._ns.nsmap())

        waypoint_identifier = SubElement(route_point, f"{{{self._ns.fpl}}}waypoint-identifier")
        waypoint_identifier.text = self.waypoint_identifier

        waypoint_type = SubElement(route_point, f"{{{self._ns.fpl}}}waypoint-type")
        waypoint_type.text = self.type_.value

        waypoint_country_code = SubElement(route_point, f"{{{self._ns.fpl}}}waypoint-country-code")
        waypoint_country_code.text = self.country_code

        return route_point


@dataclass
class Route:
    """
    FPL route.

    Representation of a base route within a FPL document.

    Name
    ----

    The FPL standard restricts route names to 25 characters, longer names will raise a ValueError exception.

    Names must consist of upper case alphanumeric characters (A-Z 0-9), or spaces (' ') as a separator, only. Names
    containing invalid characters will be silently dropped from names.

    For example a name:
    > 'FOO-bar-ABC 123 DEF 456 G' (25 characters)
    will become:
    > 'FOOABC 123 DEF 456 G' (20 characters).

    Underscores will be silently changed to spaces to aid with formatting.

    Index
    -----

    The FPL standard uses an index value to distinguish different routes, rather than route or file names. Index values
    must therefore be unique.

    Route indexes are restricted to the range 1-98 inclusive, using whole integers. Values outside this
    range will raise a ValueError.

    Waypoints
    ---------

    See the base RoutePoint class for more information.

    FPL routes may contain up to 3,000 waypoints. Where there are more a ValueError will be raised.
    """

    _ns = Namespaces()
    _max_name_length: ClassVar[int] = 25
    _min_index_count: ClassVar[int] = 1
    _max_index_count: ClassVar[int] = 98
    _max_route_waypoints: ClassVar[int] = 3_000

    name: str
    index: int
    waypoints: list[RouteWaypoint] = field(default_factory=list)

    def __post_init__(self) -> None:
        """Post-initialisation validation and processing."""
        if len(self.name) > self._max_name_length:
            msg = f"Names must be {self._max_name_length} characters or less."
            raise ValueError(msg)
        self.name = upper_alphanumeric_space_only(self.name.replace("_", " "))

        if not self._min_index_count <= self.index <= self._max_index_count:
            msg = f"Index must be between {self._min_index_count} and {self._max_index_count} inclusive."
            raise ValueError(msg)

        if len(self.waypoints) > self._max_route_waypoints:
            msg = f"Waypoints must be less than or equal to {self._max_route_waypoints}"
            raise ValueError(msg)

    @classmethod
    def loads(cls, route: BaseRoute, index: int) -> Self:
        """
        Load a base route as an FPL route.

        The FPL waypoint type is hard-coded to user defined waypoints as other types are not intended to be produced by
        this library.
        """
        return Route(
            name=route.name,
            index=index,
            waypoints=[RouteWaypoint.loads(rw) for rw in route.waypoints],
        )

    def dumps(self) -> Element:
        """Build an XML element for a FPL route."""
        route = Element(f"{{{self._ns.fpl}}}route", nsmap=self._ns.nsmap())

        route_name = SubElement(route, f"{{{self._ns.fpl}}}route-name")
        route_name.text = self.name

        route_index = SubElement(route, f"{{{self._ns.fpl}}}flight-plan-index")
        route_index.text = str(self.index)

        for route_waypoint in self.waypoints:
            route.append(route_waypoint.dumps())

        return route
